// Builds public/legacy/app.js, the page script for old browsers (Chrome 52 on Android
// TV boxes, among others), from the main script in public/index.html.
// Run with: npm run build:legacy   (after any change to the page script)
//
// The compiler, esbuild, is fetched by npx at a pinned version when this runs; it is
// a development tool only and never a dependency of the app. The output is committed,
// and a test fails while it is out of date.
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PAGE = path.join(ROOT, 'public', 'index.html');
const OUT = path.join(ROOT, 'public', 'legacy');
const ESBUILD = 'esbuild@0.25.10';
// The engine of the oldest TV boxes seen in use.
const TARGET = 'chrome52';

const sha256 = s => createHash('sha256').update(s).digest('hex');

// The page script is the one marked id="app"; the version string is in the bootstrap.
export const pageScript = html => {
  const m = html.replace(/\r\n/g, '\n').match(/<script id="app">\n([\s\S]*?)<\/script>/);
  if (!m) throw new Error('index.html: no <script id="app"> found');
  return m[1];
};
export const VERSION_RE = /var version = '([0-9a-z]+)'; \/\/ set by scripts\/build-legacy\.mjs/;
// One version for the three legacy files, so a change to any of them reaches the
// browsers that cached the others.
export const legacyVersion = files => sha256(files.join('\0')).slice(0, 12);
export const LEGACY_FILES = ['polyfills.js', 'legacy.css', 'app.js'];

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const html = fs.readFileSync(PAGE, 'utf8');
  const src = pageScript(html);
  const r = spawnSync('npx', ['--yes', ESBUILD, '--loader=js', `--target=${TARGET}`, '--charset=utf8', '--log-level=warning'], {
    input: src, encoding: 'utf8', shell: process.platform === 'win32', maxBuffer: 64 << 20,
  });
  if (r.status !== 0) { process.stderr.write(r.stderr || String(r.error)); process.exit(1); }
  if (r.stderr) process.stderr.write(r.stderr);

  const out = `// Generated by scripts/build-legacy.mjs from <script id="app"> in public/index.html
// (${ESBUILD}, --target=${TARGET}). Do not edit; run npm run build:legacy instead.
// source-sha256: ${sha256(src)}
${r.stdout}`;
  fs.writeFileSync(path.join(OUT, 'app.js'), out);

  const version = legacyVersion(LEGACY_FILES.map(f => fs.readFileSync(path.join(OUT, f), 'utf8')));
  if (!VERSION_RE.test(html)) throw new Error('index.html: the bootstrap has no version line');
  fs.writeFileSync(PAGE, html.replace(VERSION_RE, m => m.replace(/'[0-9a-z]+'/, `'${version}'`)));
  console.log(`public/legacy/app.js: ${(src.length / 1024).toFixed(0)} KB -> ${(out.length / 1024).toFixed(0)} KB, version ${version}`);
}
